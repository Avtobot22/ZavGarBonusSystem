package com.zavgar.system.config

/**
 * Контракт удалённой конфигурации приложения для общего кода.
 *
 * Чистая абстракция без привязки к провайдеру (Firebase Remote Config и т.п.).
 * Реализация живёт в инфраструктурном модуле (`:libraries:firebase`) и биндится в Koin —
 * так сетевой слой и фичи зависят от этого контракта, а не от Firebase напрямую.
 */
interface AppConfig {

    /**
     * Применяет настройки, регистрирует дефолты, фетчит и активирует значения.
     *
     * Нужно вызвать на старте приложения (до инициализации сетевого слоя), чтобы геттеры
     * отдавали актуальные серверные значения. Безопасно при оффлайне — при ошибке фетча
     * используются последние активированные или дефолтные значения.
     */
    suspend fun activate()

    /** Базовый URL сервера. */
    val baseUrl: String

    /** URL политики обработки персональных данных. */
    val privacyPolicyUrl: String

    /** Включён ли тестовый аккаунт (для автопрохождения верификации). */
    val testAccountEnabled: Boolean

    /** Номер телефона тестового аккаунта. */
    val testPhoneNumber: String

    /** OTP-код тестового аккаунта. */
    val testOtpCode: String

    /** Минимальная поддерживаемая версия приложения. */
    val minSupportedVersion: String
}
