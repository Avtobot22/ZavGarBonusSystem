package com.zavgar.system.domain.session

/**
 * Доменный порт уведомления о разлогине.
 *
 * Домен не знает об инфраструктурной шине событий (AppEventBus): он лишь сообщает
 * «пользователь разлогинен», а реализация этого порта (в композиционном слое)
 * транслирует это в нужное инфраструктурное событие.
 */
fun interface LogoutNotifier {
    /** Сообщить, что пользователь разлогинен (локальная сессия очищена). */
    fun notifyLoggedOut()
}
